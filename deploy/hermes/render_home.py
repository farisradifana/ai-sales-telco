"""Render an isolated HERMES_HOME for the TELCO deployment (Hermes Agent 0.20.5 @ 14c59f0).

  python deploy/hermes/render_home.py <out_dir>

Env (all required unless noted): ROUTER_BASE_URL (OpenAI-compatible, e.g. 9Router .../v1), ROUTER_API_KEY, MODEL_ID,
HERMES_API_KEY (API_SERVER_KEY), MCP_BRIDGE_URL (e.g. http://mcp-bridge:8765/mcp), MCP_BRIDGE_TOKEN,
HERMES_PORT (default 8642), HERMES_HOST (default 127.0.0.1; 0.0.0.0 only inside a private container network),
FALLBACK_MODEL_ID (optional).

Hardening: every builtin toolset is disabled (agent.disabled_toolsets is subtracted after all platform rules) and the
api_server platform list is an explicit empty list. The only tools are the read-only business tools of mcp_servers.telco.
The API's capability probe (GET /v1/toolsets) refuses to use Hermes if any builtin toolset shows as enabled.
Secrets go to <out_dir>/.env (mode 600); config.yaml references them as ${VAR}.
"""
import os
import sys
from pathlib import Path

BUILTIN_TOOLSETS = ['web', 'search', 'x_search', 'browser', 'terminal', 'file', 'code_execution', 'vision', 'video', 'image_gen',
                    'video_gen', 'bfl', 'tts', 'stt', 'skills', 'todo', 'memory', 'context_engine', 'session_search', 'clarify',
                    'delegation', 'cronjob', 'homeassistant', 'spotify', 'discord', 'discord_admin', 'yuanbao', 'computer_use',
                    'project', 'desktop_ui', 'kanban', 'feishu_doc', 'feishu_drive', 'debugging', 'safe', 'coding']


def main(out: Path):
    e = os.environ
    need = ['ROUTER_BASE_URL', 'ROUTER_API_KEY', 'MODEL_ID', 'HERMES_API_KEY', 'MCP_BRIDGE_URL', 'MCP_BRIDGE_TOKEN']
    missing = [k for k in need if not e.get(k)]
    if missing:
        sys.exit('missing env: ' + ', '.join(missing))
    out.mkdir(parents=True, exist_ok=True)
    disabled = '\n'.join(f'    - {t}' for t in BUILTIN_TOOLSETS)
    fallback = f"\n  fallback_models:\n    - provider: custom\n      model: {e['FALLBACK_MODEL_ID']}\n      base_url: {e['ROUTER_BASE_URL']}\n" \
        if e.get('FALLBACK_MODEL_ID') else ''
    (out / 'config.yaml').write_text(f"""# Generated by deploy/hermes/render_home.py - do not hand-edit in production.
model:
  default: {e['MODEL_ID']}
  provider: custom
  base_url: {e['ROUTER_BASE_URL']}
  api_key: ${{ROUTER_API_KEY}}{fallback}
agent:
  max_turns: 6
  disabled_toolsets:
{disabled}
platform_toolsets:
  api_server: []
tools:
  tool_search:
    enabled: "off"   # expose the 6 business tool schemas directly (fixed, auditable catalog; no lazy bridge)
memory:
  memory_enabled: false
  user_profile_enabled: false
gateway:
  api_server:
    enabled: true
    host: {e.get('HERMES_HOST', '127.0.0.1')}
    port: {e.get('HERMES_PORT', '8642')}
    max_concurrent_runs: 8
mcp_servers:
  telco:
    url: {e['MCP_BRIDGE_URL']}
    headers:
      Authorization: "Bearer ${{MCP_BRIDGE_TOKEN}}"
    timeout: 60
    connect_timeout: 20
    # First-party bridge exposing only read-only business tools; authorization is enforced by the API per ticket.
    # 'untrusted' would be preferable, but Hermes 0.20.5 + mcp 2.0.0 reads annotations.readOnlyHint (camelCase) while
    # the SDK object exposes read_only_hint, so every tool looks write-capable and the API-server gateway (no human
    # approval surface) fails closed. Revisit when upstream fixes tools/mcp_tool.py::_annotation_read_only_hint.
    trust: full
    tools:
      include: [get_evidence, diagnose, rank_districts, rank_regencies, stock, target, resolve_entity]
      resources: false
      prompts: false
""", encoding='utf-8')
    env = out / '.env'
    env.write_text(f"API_SERVER_ENABLED=true\nAPI_SERVER_KEY={e['HERMES_API_KEY']}\nAPI_SERVER_PORT={e.get('HERMES_PORT', '8642')}\n"
                   f"API_SERVER_HOST={e.get('HERMES_HOST', '127.0.0.1')}\nROUTER_API_KEY={e['ROUTER_API_KEY']}\n"
                   f"MCP_BRIDGE_TOKEN={e['MCP_BRIDGE_TOKEN']}\n", encoding='utf-8')
    try:
        os.chmod(env, 0o600)
    except OSError:
        pass
    (out / 'SOUL.md').write_text('Asisten analitik TELCO. Hanya gunakan tool bisnis read-only; angka hanya dari tool.\n', encoding='utf-8')
    print('rendered', out)


if __name__ == '__main__':
    main(Path(sys.argv[1]))
